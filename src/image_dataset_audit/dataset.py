"""
Shared paths and loaders for the Food-101 dataset.
"""

import json
import random
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]  # repo root
DATA = ROOT / "data" / "food-101"
IMAGES = DATA / "images"  # images/<class_name>/<image_id>.jpg
REPORTS = ROOT / "reports"  # small results for readers: summaries, plots (committed)
OUTPUTS = ROOT / "outputs"  # per-image tables, regenerated by scripts (git-ignored)

SEED = 42  # default seed for samples, so every script picks the same files


def list_images() -> list[Path]:
    """Every image file under IMAGES, sorted.

    glob returns files in filesystem order, which is not guaranteed to repeat;
    sorting makes the list, and so any seeded sample of it, the same every run.
    """
    files = sorted(p for p in IMAGES.glob("*/*") if p.is_file())
    if not files:
        raise FileNotFoundError(f"No files found under {IMAGES}")
    return files


def sample_images(n: int, seed: int = SEED) -> list[Path]:
    """A random sample of n image files (all of them if n is larger).

    Same n and seed give the same files in the same order.
    """
    files = list_images()
    return random.Random(seed).sample(files, min(n, len(files)))


def load_split(split: str) -> pd.DataFrame:
    """Return one row per image listed in meta/<split>.json."""
    with open(DATA / "meta" / f"{split}.json") as f:
        mapping = json.load(f)

    rows = []
    for class_name, image_ids in mapping.items():
        for image_id in image_ids:
            rows.append({"image_id": image_id, "class": class_name, "split": split})
    return pd.DataFrame(rows)


def load_meta() -> pd.DataFrame:
    """Both splits in one table."""
    return pd.concat([load_split("train"), load_split("test")], ignore_index=True)
